/* =========================================================================
 * 5. New pages: hubs, condition library, clinician, team, FAQ
 * ========================================================================= */
function physio_mk_page( $slug, $title, $content, $parent_slug = '' ) {
	$full     = $parent_slug ? $parent_slug . '/' . $slug : $slug;
	$existing = get_page_by_path( $full );
	if ( $existing ) {
		echo "page exists: $full\n";
		return $existing->ID;
	}
	$parent_id = 0;
	if ( $parent_slug ) {
		$parent = get_page_by_path( $parent_slug );
		if ( ! $parent ) { echo "PARENT MISSING: $parent_slug for $slug\n"; return 0; }
		$parent_id = $parent->ID;
	}
	$id = wp_insert_post( array(
		'post_type'    => 'page',
		'post_status'  => 'publish',
		'post_name'    => $slug,
		'post_title'   => $title,
		'post_content' => $content,
		'post_parent'  => $parent_id,
	) );
	echo "created page: $slug (#$id)\n";
	return $id;
}

